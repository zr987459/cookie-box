package com.cookiebox.app.engine

import com.cookiebox.app.model.CookieItem
import java.net.URI

object CookieFormatter {

    /**
     * 生成 HTTP 请求头格式的 Cookie 字符串 (用于 Header 'Cookie: ...')
     */
    fun toHeaderString(items: List<CookieItem>): String {
        return items.joinToString("; ") { "${it.name}=${it.value}" }
    }

    /**
     * 生成结构化 JSON 格式
     */
    fun toJson(items: List<CookieItem>): String {
        val sb = StringBuilder("[\n")
        items.forEachIndexed { index, item ->
            val escapedValue = item.value.replace("\\", "\\\\").replace("\"", "\\\"")
            val escapedName = item.name.replace("\\", "\\\\").replace("\"", "\\\"")
            sb.append("  {\n")
            sb.append("    \"name\": \"$escapedName\",\n")
            sb.append("    \"value\": \"$escapedValue\",\n")
            sb.append("    \"domain\": \"${item.domain}\",\n")
            sb.append("    \"path\": \"${item.path}\"\n")
            sb.append("  }")
            if (index < items.size - 1) sb.append(",")
            sb.append("\n")
        }
        sb.append("]")
        return sb.toString()
    }

    /**
     * 生成标准 Netscape / cookies.txt 格式 (yt-dlp, curl, wget 兼容)
     */
    fun toNetscape(items: List<CookieItem>, fallbackDomain: String): String {
        val sb = StringBuilder()
        sb.append("# Netscape HTTP Cookie File\n")
        sb.append("# Generated by CookieBox\n")
        sb.append("# domain\tinclude_subdomains\tpath\tsecure\texpiry\tname\tvalue\n")

        val expiry = (System.currentTimeMillis() / 1000) + 31536000L // 1 年后

        for (item in items) {
            val d = if (item.domain.isNotEmpty()) {
                if (item.domain.startsWith(".")) item.domain else ".${item.domain}"
            } else {
                if (fallbackDomain.startsWith(".")) fallbackDomain else ".$fallbackDomain"
            }
            sb.append("$d\tTRUE\t/\tFALSE\t$expiry\t${item.name}\t${item.value}\n")
        }
        return sb.toString()
    }

    /**
     * 生成可直接运行的 Python Requests 爬虫模版
     */
    fun toPythonSnippet(items: List<CookieItem>, url: String, userAgent: String): String {
        val cookieHeader = toHeaderString(items).replace("\"", "\\\"")
        val safeUa = userAgent.replace("\"", "\\\"")
        val targetUrl = if (url.isBlank()) "https://example.com" else url

        return """
# -*- coding: utf-8 -*-
# Generated by CookieBox
import requests

url = "$targetUrl"

headers = {
    "User-Agent": "$safeUa",
    "Cookie": "$cookieHeader"
}

response = requests.get(url, headers=headers, timeout=15)
print("状态码:", response.status_code)
print("响应内容:", response.text[:300])
        """.trimIndent()
    }

    /**
     * 生成完整的 cURL 命令
     */
    fun toCurlCommand(items: List<CookieItem>, url: String, userAgent: String): String {
        val cookieHeader = toHeaderString(items).replace("'", "'\\''")
        val safeUa = userAgent.replace("'", "'\\''")
        val targetUrl = if (url.isBlank()) "https://example.com" else url

        return "curl '$targetUrl' \\\n" +
                "  -H 'User-Agent: $safeUa' \\\n" +
                "  -H 'Cookie: $cookieHeader'"
    }
}
